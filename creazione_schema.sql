

CREATE TABLE TipoSoggettoNIS (
    id          NUMBER(5) PRIMARY KEY,
    codice      VARCHAR2(20) NOT NULL UNIQUE
                CHECK (codice IN ('ESSENZIALE', 'IMPORTANTE')),
    descrizione VARCHAR2(255)
);
 

CREATE TABLE RegistroTabelle (
    id           NUMBER(5) PRIMARY KEY,
    nome_tabella VARCHAR2(100) NOT NULL UNIQUE
);


CREATE TABLE LogEstrazione (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_tabella_id NUMBER(5) NOT NULL REFERENCES RegistroTabelle(id),
    record_id           NUMBER(19) NOT NULL,          -- riferimento debole, non FK
    utente              VARCHAR2(100) NOT NULL,
    data_ora            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    tipo_operazione     VARCHAR2(30) NOT NULL
                        CHECK (tipo_operazione IN
                            ('INSERIMENTO', 'MODIFICA', 'ESTRAZIONE_CSV', 'CONSULTAZIONE')),
    snapshot_dati       CLOB                     -- opzionale, copia dei dati al momento del log
);
 
CREATE INDEX idx_logestrazione_tabella_record
    ON LogEstrazione (registro_tabella_id, record_id);
CREATE INDEX idx_logestrazione_data
    ON LogEstrazione (data_ora);


CREATE TABLE SoggettoNIS (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codice_fiscale      VARCHAR2(16) NOT NULL UNIQUE,
    denominazione       VARCHAR2(255) NOT NULL,
    indirizzo_sede_legale VARCHAR2(255) NOT NULL,
    pec                 VARCHAR2(255) NOT NULL,
    email_funzionale    VARCHAR2(255),
    telefono            VARCHAR2(30),
    fatturato           NUMERIC(15,2),          -- nullable: PA esente (vedi campi_dati.md §2)
    bilancio            NUMERIC(15,2),           -- nullable: PA esente
    n_dipendenti        NUMBER(10),
    tipo_soggetto_id    NUMBER(5) NOT NULL REFERENCES TipoSoggettoNIS(id),
    data_creazione      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
 
CREATE INDEX idx_soggettonis_tipo ON SoggettoNIS (tipo_soggetto_id);
  

CREATE TABLE SoggettoNISStorico (
    id                      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    soggetto_nis_id         NUMBER(19) NOT NULL REFERENCES SoggettoNIS(id),
    versione                NUMBER(10) NOT NULL,
    denominazione           VARCHAR2(255) NOT NULL,
    indirizzo_sede_legale   VARCHAR2(255) NOT NULL,
    pec                     VARCHAR2(255) NOT NULL,
    email_funzionale        VARCHAR2(255),
    telefono                VARCHAR2(30),
    fatturato               NUMERIC(15,2),
    bilancio                NUMERIC(15,2),
    n_dipendenti            NUMBER(10),
    tipo_soggetto_id        NUMBER(5) NOT NULL REFERENCES TipoSoggettoNIS(id),
    valido_da               TIMESTAMP NOT NULL,
    valido_a                TIMESTAMP,           -- NULL se è la versione più recente
    log_estrazione_id       NUMBER(19) NOT NULL REFERENCES LogEstrazione(id),
    UNIQUE (soggetto_nis_id, versione)
);
 
CREATE INDEX idx_soggettonisstorico_soggetto ON SoggettoNISStorico (soggetto_nis_id);
CREATE INDEX idx_soggettonisstorico_validita ON SoggettoNISStorico (soggetto_nis_id, valido_da, valido_a);
 
 

