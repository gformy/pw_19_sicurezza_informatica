    PRIMARY KEY (tipo_incidente_id, tipo_soggetto_id)
);
 

CREATE TABLE CategoriaIncidente (
    id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR2(50) NOT NULL UNIQUE
);
 

CREATE TABLE Incidente (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_incidente_id   NUMBER(19) NOT NULL REFERENCES TipoIncidente(id),
    soggetto_nis_id     NUMBER(19) NOT NULL REFERENCES SoggettoNIS(id),
    categoria_id        NUMBER(19) REFERENCES CategoriaIncidente(id),   -- nullable: non sempre nota da subito
