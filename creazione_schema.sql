-- ---------------------------------------------------------------------
-- Sequenza condivisa: garantisce id univoci tra Asset e Servizio,
-- necessaria per la chiave primaria condivisa (class-table inheritance).
-- ---------------------------------------------------------------------
CREATE SEQUENCE seq_elemento_critico;
 

CREATE TABLE ElementoCritico (
    id                  NUMBER(19) DEFAULT seq_elemento_critico.NEXTVAL PRIMARY KEY,
    tipo                VARCHAR2(10) NOT NULL CHECK (tipo IN ('ASSET', 'SERVIZIO')),
    nome                VARCHAR2(255) NOT NULL,
    soggetto_nis_id     NUMBER(19) NOT NULL REFERENCES SoggettoNIS(id),
    stato               VARCHAR2(10) DEFAULT 'ATTIVO' NOT NULL
                        CHECK (stato IN ('ATTIVO', 'DISMESSO')),
    data_inizio_validita TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    data_fine_validita  TIMESTAMP              -- NULL se attivo
);
 
CREATE INDEX idx_elementocritico_soggetto ON ElementoCritico (soggetto_nis_id);
CREATE INDEX idx_elementocritico_tipo ON ElementoCritico (tipo);
 

CREATE TABLE ElementoCriticoStorico (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    elemento_critico_id NUMBER(19) NOT NULL REFERENCES ElementoCritico(id),
    versione            NUMBER(10) NOT NULL,
    nome                VARCHAR2(255) NOT NULL,
    soggetto_nis_id     NUMBER(19) NOT NULL REFERENCES SoggettoNIS(id),
    stato               VARCHAR2(10) NOT NULL,
    valido_da           TIMESTAMP NOT NULL,
    valido_a            TIMESTAMP,
    log_estrazione_id   NUMBER(19) NOT NULL REFERENCES LogEstrazione(id),
    UNIQUE (elemento_critico_id, versione)
);
 
CREATE INDEX idx_elementocriticostorico_elemento ON ElementoCriticoStorico (elemento_critico_id);
CREATE INDEX idx_elementocriticostorico_validita ON ElementoCriticoStorico (elemento_critico_id, valido_da, valido_a);
 
 
CREATE TABLE Asset (
    id          NUMBER(19) PRIMARY KEY REFERENCES ElementoCritico(id),
    tipo_asset  VARCHAR2(20) NOT NULL
                CHECK (tipo_asset IN ('HARDWARE', 'SOFTWARE', 'FLUSSO_RETE', 'SERVIZIO_FORNITORE')),
    rilevante   NUMBER(1) DEFAULT 0 NOT NULL
                CHECK (rilevante IN (0,1))  -- "sistemi informativi e di rete rilevanti", GV.OC-4
);
 
 
-- ---------------------------------------------------------------------
-- Servizio — sottoclasse (categorizzazione art. 20-21 piattaforma ACN)
-- ---------------------------------------------------------------------
CREATE TABLE Servizio (
    id                  NUMBER(19) PRIMARY KEY REFERENCES ElementoCritico(id),
    descrizione         VARCHAR2(500),
    categoria_rilevanza VARCHAR2(50)              -- nullable: modello ACN non ancora definitivo alla data di raccolta fonti
);
 
 
CREATE TABLE ServizioStatoMembro (
    servizio_id     NUMBER(19) NOT NULL REFERENCES Servizio(id),
    stato_membro    CHAR(2) NOT NULL,           -- codice ISO 3166-1 alpha-2
    PRIMARY KEY (servizio_id, stato_membro)
);
 

CREATE TABLE AssetServizio (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id    NUMBER(19) NOT NULL REFERENCES Asset(id),
    servizio_id NUMBER(19) NOT NULL REFERENCES Servizio(id),
    stato       VARCHAR2(10) DEFAULT 'ATTIVA' NOT NULL
                CHECK (stato IN ('ATTIVA', 'CESSATA')),
    UNIQUE (asset_id, servizio_id)               -- una sola relazione "corrente" per coppia
);
 
CREATE INDEX idx_assetservizio_asset ON AssetServizio (asset_id);
CREATE INDEX idx_assetservizio_servizio ON AssetServizio (servizio_id);
 
CREATE TABLE AssetServizioStorico (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_servizio_id   NUMBER(19) NOT NULL REFERENCES AssetServizio(id),
    versione            NUMBER(10) NOT NULL,
    stato               VARCHAR2(10) NOT NULL,
    valido_da           TIMESTAMP NOT NULL,
    valido_a            TIMESTAMP,
    log_estrazione_id   NUMBER(19) NOT NULL REFERENCES LogEstrazione(id),
    UNIQUE (asset_servizio_id, versione)
);
 
CREATE INDEX idx_assetserviziostorico_rel ON AssetServizioStorico (asset_servizio_id);


