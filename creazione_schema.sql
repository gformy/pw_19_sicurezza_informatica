    gravita             VARCHAR2(20)
                        CHECK (gravita IN ('BASSA', 'MEDIA', 'ALTA', 'CRITICA')),
    root_cause          VARCHAR2(500)              -- testo libero: causa originaria, spesso nota solo a posteriori
);
 
CREATE INDEX idx_incidente_soggetto ON Incidente (soggetto_nis_id);
CREATE INDEX idx_incidente_data ON Incidente (data_evidenza);
 
 
